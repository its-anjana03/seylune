// =====================================================================
// SEYLUNE — build supabase/05-outerwear-and-accessories.sql
//
//   node supabase/make-new-collections.js
//
// Adds the Outerwear and Accessories pieces from shared/products.js to
// the database, whole (price, colour, sizes, photos, descriptions), with
// a starting stock count for each size. Also adds the two new views of
// the Noira Satin Dress.
//   - Pieces already in the database are left alone, so running it again
//     never overwrites what an admin has edited since.
//   - Stock is only set for sizes that have none yet: it never undoes sales.
// The starting stock uses the same made-up but stable numbers as
// make-seed.js (the shop shows the same numbers before the database answers).
// =====================================================================
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const root = path.join(__dirname, "..");
const ctx = {};
vm.runInNewContext(
  fs.readFileSync(path.join(root, "shared/products.js"), "utf8") + "\nthis.P = SEYLUNE_PRODUCTS;",
  ctx
);

const CATEGORIES = ["Outerwear", "Accessories"];

const q = s => s == null ? "null" : "'" + String(s).replace(/'/g, "''") + "'";
const arr = list => "array[" + (list || []).map(q).join(", ") + "]::text[]";

// Same as make-seed.js and Seylune.stockLeft before the database answers
function stockFor(id, size) {
  let h = 2166136261;
  for (const ch of id + "|" + size) h = Math.imul(h ^ ch.charCodeAt(0), 16777619);
  const n = Math.abs(h) % 20;
  if (n < 2) return 0;
  if (n < 5) return n - 1;
  return 4 + (n % 7);
}

// Each piece keeps its place in shared/products.js (10, 20, 30 …)
const pieces = ctx.P
  .map((p, i) => ({ ...p, sortOrder: (i + 1) * 10 }))
  .filter(p => CATEGORIES.includes(p.category));

const rows = pieces.map(p => `  (${q(p.id)}, ${q(p.name)}, ${q(p.category)}, ${Number(p.price)},
   ${q(p.color)}, ${arr(p.sizes)}, ${p.isNew ? "true" : "false"},
   ${q(p.image)},
   ${arr(p.gallery)},
   ${q(p.short)},
   ${q(p.description)},
   ${q(p.fabric)}, ${q(p.care)}, ${q(p.note)}, ${p.sortOrder})`).join(",\n");

const stock = pieces.flatMap(p => p.sizes.map(s =>
  `  (${q(p.id)}, ${q(s)}, ${stockFor(p.id, s)})`)).join(",\n");

const noira = ctx.P.find(p => p.id === "noira-satin-dress");
// Noira's three photos as they were before step 9 (they lived in the old
// "Prodcut Details-Noira Satin Dress/" folder, renamed in step 10)
const oldNoiraGallery = [
  "Prodcut Details-Noira Satin Dress/Noira-Satin-Dress-2.jpg",
  "Prodcut Details-Noira Satin Dress/Noira-Satin-Dress-1.jpg",
  "Prodcut Details-Noira Satin Dress/Noira-Satin-Dress-3.jpg"
];

const sql = `-- =====================================================================
-- SEYLUNE — STEP 9: THE OUTERWEAR + ACCESSORIES COLLECTIONS
-- Generated by supabase/make-new-collections.js from shared/products.js.
-- Run once (SQL Editor → + → Create a new snippet → paste → Run).
--
-- Adds ${pieces.length} pieces (${CATEGORIES.join(" and ")}) with their photos, sizes and
-- starting stock, and two more views of the Noira Satin Dress.
-- Safe to run again: pieces and stock already in the database are left
-- exactly as they are (an admin's edits and real sales are kept).
-- =====================================================================

-- 1. The pieces
insert into public.products
  (id, name, category, price, color, sizes, is_new, image, gallery, short, description, fabric, care, note, sort_order)
values
${rows}
on conflict (id) do nothing;

-- 2. Starting stock for each size
insert into public.product_stock (product_id, size, quantity) values
${stock}
on conflict (product_id, size) do nothing;

-- 3. The Noira Satin Dress gains a back view and a close-up
--    (only if its photos haven't been changed on the admin page)
update public.products
   set gallery = ${arr(noira.gallery)},
       updated_at = now()
 where id = 'noira-satin-dress'
   and gallery = ${arr(oldNoiraGallery)};
`;

fs.writeFileSync(path.join(__dirname, "05-outerwear-and-accessories.sql"), sql);
console.log(`05-outerwear-and-accessories.sql written: ${pieces.length} pieces, ${pieces.reduce((n, p) => n + p.sizes.length, 0)} sizes`);
