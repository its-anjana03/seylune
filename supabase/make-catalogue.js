// =====================================================================
// SEYLUNE — build supabase/03-catalogue-content.sql from shared/products.js
//
//   node supabase/make-catalogue.js
//
// Copies each piece's description, colour, sizes, photos and "new"
// flag into the products table (step 3). It only fills pieces that have
// no photo in the database yet, so running it again never overwrites
// what an admin has edited since.
// =====================================================================
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const root = path.join(__dirname, "..");
const ctx = {};
vm.runInNewContext(
  fs.readFileSync(path.join(root, "shared/products.js"), "utf8") + "\nthis.P = SEYLUNE_PRODUCTS;",
  ctx
);

const q = s => s == null ? "null" : "'" + String(s).replace(/'/g, "''") + "'";
const arr = list => "array[" + (list || []).map(q).join(", ") + "]::text[]";

const updates = ctx.P.map((p, i) => `update public.products set
  color = ${q(p.color)}, sizes = ${arr(p.sizes)}, is_new = ${p.isNew ? "true" : "false"},
  image = ${q(p.image)}, gallery = ${arr(p.gallery)},
  short = ${q(p.short)}, description = ${q(p.description)},
  fabric = ${q(p.fabric)}, care = ${q(p.care)}, note = ${q(p.note)},
  sort_order = ${(i + 1) * 10}, updated_at = now()
where id = ${q(p.id)} and image is null;`).join("\n\n");

const sql = `-- =====================================================================
-- SEYLUNE — COPY THE PIECES' DETAILS INTO THE DATABASE (step 3, part 2)
-- Generated by supabase/make-catalogue.js from shared/products.js.
-- Run after 03-catalogue-and-shop-tools.sql. Only fills pieces that have
-- no photo in the database yet, so it never overwrites admin edits.
-- =====================================================================

${updates}
`;

fs.writeFileSync(path.join(__dirname, "03-catalogue-content.sql"), sql);
console.log(`03-catalogue-content.sql written: ${ctx.P.length} pieces`);
