// =====================================================================
// SEYLUNE — build supabase/seed.sql from shared/products.js
//
//   node supabase/make-seed.js
//
// Writes the price list (products) and a starting stock count for every
// size. Run it again whenever you add pieces to shared/products.js, then
// paste the new seed.sql into the Supabase SQL Editor.
//   - Prices and names are updated if they changed.
//   - Stock is only set for NEW sizes: re-running never undoes sales.
// The starting stock is made up but stable (the same every run): most
// sizes have a few pieces, some are low and a handful are sold out, so
// the "Only 2 left" and "Sold out" states can be seen on the site.
// =====================================================================
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const root = path.join(__dirname, "..");
const ctx = {};
vm.runInNewContext(
  fs.readFileSync(path.join(root, "shared/products.js"), "utf8") + "\nthis.P = SEYLUNE_PRODUCTS;",
  ctx
);

const q = s => "'" + String(s).replace(/'/g, "''") + "'";

// Small stable hash → the same "random" stock every time
function stockFor(id, size) {
  let h = 2166136261;
  for (const ch of id + "|" + size) h = Math.imul(h ^ ch.charCodeAt(0), 16777619);
  const n = Math.abs(h) % 20;
  if (n < 2) return 0;        // ~10% sold out
  if (n < 5) return n - 1;    // ~15% low (1–3 left)
  return 4 + (n % 7);         // the rest: 4–10
}

const products = ctx.P.map(p =>
  `  (${q(p.id)}, ${q(p.name)}, ${q(p.category)}, ${Number(p.price)})`).join(",\n");

const stock = ctx.P.flatMap(p => p.sizes.map(s =>
  `  (${q(p.id)}, ${q(s)}, ${stockFor(p.id, s)})`)).join(",\n");

const sql = `-- =====================================================================
-- SEYLUNE — PRICE LIST + STARTING STOCK
-- Generated by supabase/make-seed.js from shared/products.js — do not edit
-- by hand. Run after schema.sql (SQL Editor → New query → Run).
-- =====================================================================

insert into public.products (id, name, category, price) values
${products}
on conflict (id) do update
  set name = excluded.name, category = excluded.category,
      price = excluded.price, active = true;

-- Pieces no longer in the catalogue stop being sold (old orders keep them)
update public.products set active = false
 where id not in (${ctx.P.map(p => q(p.id)).join(", ")});

insert into public.product_stock (product_id, size, quantity) values
${stock}
on conflict (product_id, size) do nothing;
`;

fs.writeFileSync(path.join(__dirname, "seed.sql"), sql);
console.log(`seed.sql written: ${ctx.P.length} products, ${ctx.P.reduce((n, p) => n + p.sizes.length, 0)} sizes`);
