// =====================================================================
// SEYLUNE — build sitemap.xml (the list of pages for search engines)
//
//   node tools/make-sitemap.js
//
// Lists every public page plus one address per piece in
// shared/products.js. Run it again after adding pieces, then push.
// Private pages (cart, checkout, account, search results, admin) are
// left out on purpose; they also carry a "noindex" tag.
// =====================================================================
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const SITE = "https://its-anjana03.github.io/seylune/";
const root = path.join(__dirname, "..");
const ctx = {};
vm.runInNewContext(fs.readFileSync(path.join(root, "shared/products.js"), "utf8") + "\nthis.P = SEYLUNE_PRODUCTS;", ctx);

const today = new Date().toISOString().slice(0, 10);
const pages = [
  ["home/home.html", "1.0"],
  ["Collections/collections.html", "0.9"],
  ["New-Arrivals/new-arrivals.html", "0.9"],
  ["Dresses/dresses.html", "0.8"],
  ["Tops/tops.html", "0.8"],
  ["Bottoms/bottoms.html", "0.8"],
  ["Outerwear/outerwear.html", "0.8"],
  ["Accessories/accessories.html", "0.8"],
  ["About/About.html", "0.5"]
].concat(ctx.P.map(p => ["Product/product.html?id=" + encodeURIComponent(p.id), "0.6"]));

const xml = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by tools/make-sitemap.js -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${pages.map(([url, priority]) => `  <url><loc>${SITE}${url.replace(/&/g, "&amp;")}</loc><lastmod>${today}</lastmod><priority>${priority}</priority></url>`).join("\n")}
</urlset>
`;

fs.writeFileSync(path.join(root, "sitemap.xml"), xml);
console.log(`sitemap.xml written: ${pages.length} addresses`);
